/**
 * Post-build workaround for vite-plugin-pwa + Vite 8 (Rolldown) incompatibility.
 *
 * vite-plugin-pwa uses `bundle[filename] = ...` to emit registerSW.js and manifest.webmanifest
 * during generateBundle, which Rolldown does not support. The plugin logs a warning
 * and silently drops the files. This script writes them manually after the build.
 *
 * Remove this script once vite-plugin-pwa natively supports Rolldown / Vite 8.
 */
import { writeFileSync, mkdirSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const distDir = resolve(__dirname, '../dist')

mkdirSync(distDir, { recursive: true })

// This is the standard registerSW.js content generated by vite-plugin-pwa
// when registerType is 'autoUpdate'.
const registerSW = `
if ('serviceWorker' in navigator) {
  window.addEventListener('load', () => {
    navigator.serviceWorker.register('/sw.js', { scope: '/' })
      .then((registration) => {
        registration.addEventListener('updatefound', () => {
          const newWorker = registration.installing
          if (!newWorker) return
          newWorker.addEventListener('statechange', () => {
            if (newWorker.state === 'installed' && navigator.serviceWorker.controller) {
              // New content available - auto-reload (matches registerType: 'autoUpdate')
              window.location.reload()
            }
          })
        })
      })
      .catch((error) => {
        console.error('Service worker registration failed:', error)
      })
  })
}
`.trimStart()

const manifest = {
  name: 'Barcoded',
  short_name: 'Barcoded',
  description: 'Generate and manage barcodes and QR codes locally — no data leaves your device.',
  theme_color: '#ffffff',
  background_color: '#ffffff',
  display: 'standalone',
  start_url: '/',
  icons: [
    {
      src: 'pwa-64x64.png',
      sizes: '64x64',
      type: 'image/png'
    },
    {
      src: 'pwa-192x192.png',
      sizes: '192x192',
      type: 'image/png'
    },
    {
      src: 'pwa-512x512.png',
      sizes: '512x512',
      type: 'image/png'
    },
    {
      src: 'maskable-icon-512x512.png',
      sizes: '512x512',
      type: 'image/png',
      purpose: 'maskable'
    }
  ]
}

writeFileSync(resolve(distDir, 'registerSW.js'), registerSW)
console.log('✓ registerSW.js written to dist/')

writeFileSync(resolve(distDir, 'manifest.webmanifest'), JSON.stringify(manifest, null, 2))
console.log('✓ manifest.webmanifest written to dist/')

